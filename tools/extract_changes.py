#!/usr/bin/env python3
"""Extract every '// MineX start' .. '// MineX end' block from the source trees.

`folia-server/src/minecraft` is generated by paperweight from the patch stack and
is gitignored, so there is no committed baseline tree to `git diff` against
without a 20+ minute applyAllPatches. The change blocks are therefore delimited
in-source with markers, and this extracts them verbatim so the reference doc can
show exactly what was changed, with file and line numbers.

usage:
  python extract_changes.py --root <src-root> --out <json>
"""
import argparse
import json
import os
import re

START = re.compile(r'//\s*MineX start\s*-*\s*(.*)$', re.I)
END = re.compile(r'//\s*MineX end', re.I)


def walk(root):
    for dirpath, _dirnames, filenames in os.walk(root):
        for fn in filenames:
            if fn.endswith('.java'):
                yield os.path.join(dirpath, fn)


def extract(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        lines = f.read().split('\n')
    blocks = []
    i = 0
    while i < len(lines):
        m = START.search(lines[i])
        if not m:
            i += 1
            continue
        title = (m.group(1) or '').strip(' -')
        start = i
        j = i + 1
        while j < len(lines) and not END.search(lines[j]):
            j += 1
        body = lines[start:j + 1]
        blocks.append({
            'file': path,
            'line': start + 1,
            'lines': len(body),
            'title': title or '(untitled)',
            'code': '\n'.join(body),
        })
        i = j + 1
    return blocks


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--root', action='append', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()

    out = []
    for root in a.root:
        for p in walk(root):
            out.extend(extract(p))

    # add files that are entirely new (no upstream counterpart)
    with open(a.out, 'w', encoding='utf-8') as f:
        json.dump(out, f, indent=1)

    by_file = {}
    for b in out:
        by_file.setdefault(b['file'], []).append(b)
    total = sum(b['lines'] for b in out)
    print(f'{len(out)} blocks across {len(by_file)} files, {total} lines total')
    for p, bs in sorted(by_file.items()):
        print(f'  {len(bs):>2} block(s)  {sum(x["lines"] for x in bs):>4} lines  {os.path.basename(p)}')


if __name__ == '__main__':
    main()
